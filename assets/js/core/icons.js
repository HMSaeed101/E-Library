/**
 * Utility to inject an icon into an element
 * @param {string} name - Icon key from ICONS
 * @param {string} className - Optional CSS class
 * @returns {string} - SVG string wrapped in a span
 */
export function getIcon(name, className = "") {
    const icon = ICONS[name];
    if (!icon) return "";
    return `<span class="icon-wrapper ${className}">${icon}</span>`;
}
